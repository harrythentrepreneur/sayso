def run_suite(where: Path, *, failfast: bool = False) -> subprocess.CompletedProcess:
    """failfast is for mutants only: a mutant needs ONE red test to be killed, so the run
    stops at the first failure. The baseline and equivalents always run in full."""
    return subprocess.run([sys.executable, "-m", "unittest", "discover", "-s", "tests", "-t", ".",
                           *(["-f"] if failfast else [])],
                          cwd=where, capture_output=True, text=True, timeout=600)


def _one(tmp: str, base: Path, i: int, rel: str, old: str, new: str,
         failfast: bool = True) -> tuple[str, str | None]:
    """Apply one mutation in its OWN scratch copy and run the suite.
    Returns ("stale", n) | ("killed", first failing line) | ("survived", None)."""
    work = Path(tmp) / f"work-{i}"
    shutil.copytree(base, work)
    try:
        path = work / rel
        text = path.read_text()
        if text.count(old) != 1:
            return "stale", str(text.count(old))
        path.write_text(text.replace(old, new))
        result = run_suite(work, failfast=failfast)
        if result.returncode != 0:
            return "killed", next((ln for ln in result.stderr.splitlines() if ln.startswith(("FAIL:", "ERROR:"))), "?")
        return "survived", None
    finally:
        shutil.rmtree(work, ignore_errors=True)


def shard() -> tuple[int, int]:
    """MUTATE_SHARD="k/n" (1-based) runs every n-th entry starting at k, so n CI jobs share the list.
    Unset means the whole list. A malformed value fails loudly rather than silently testing less."""
    raw = os.environ.get("MUTATE_SHARD", "").strip()
    if not raw:
        return 0, 1
    k, _, n = raw.partition("/")
    k, n = int(k), int(n)
    if not 1 <= k <= n:
        raise SystemExit(f"MUTATE_SHARD={raw!r}: need k/n with 1 <= k <= n")
    return k - 1, n


def workers() -> int:
    """Parallel suite runs. MUTATE_JOBS overrides; default = CPUs, at most 8."""
    return max(1, int(os.environ.get("MUTATE_JOBS") or min(8, os.cpu_count() or 1)))


def main() -> int:
    with tempfile.TemporaryDirectory(prefix="sayso-mutate-") as tmp:
        base = Path(tmp) / "base"
        shutil.copytree(ROOT, base, ignore=shutil.ignore_patterns(".git", "__pycache__", "*.pyc"))
        baseline = run_suite(base)
        if baseline.returncode != 0:
            print(baseline.stderr[-3000:])
            print("MUTATION VERDICT: FAIL baseline not green; harness proves nothing")
            return 2
        jobs = workers()
        print(f"baseline green; {len(MUTATIONS)} mutations + {len(EQUIVALENT)} equivalents on {jobs} workers", flush=True)
        everything = [(n, r, o, w, False) for n, r, o, w in MUTATIONS] + [(n, r, o, w, True) for n, r, o, w in EQUIVALENT]
        index, count = shard()
        everything = [e for i, e in enumerate(everything) if i % count == index]   # every entry in exactly one shard
        if count > 1:
            print(f"shard {index + 1}/{count}: {len(everything)} entries", flush=True)
        with ThreadPoolExecutor(max_workers=jobs) as pool:
            futures = [pool.submit(_one, tmp, base, i, r, o, w, not eq) for i, (_, r, o, w, eq) in enumerate(everything)]
            results = [f.result() for f in futures]          # report in list order, whatever finished first
        killed, survived = 0, []
        for (name, _, _, _, equivalent), (outcome, detail) in zip(everything, results):
            if equivalent:
                if outcome == "survived":
                    print(f"EQUIVALENT {name}")
                else:
                    survived.append(f"{name} (listed equivalent but now {outcome}; re-check the list)")
                    print(f"CHANGED   {name}  <- {detail}")
            elif outcome == "stale":
                survived.append(f"{name} (pattern found {detail} times; harness stale)")
                print(f"STALE     {name}")
            elif outcome == "killed":
                killed += 1
                print(f"KILLED    {name}  <- {detail}")
            else:
                survived.append(name)
                print(f"SURVIVED  {name}")
        total = sum(1 for e in everything if not e[4])
        verdict = "PASS" if not survived else "FAIL"
        print(f"MUTATION VERDICT: {verdict} {killed}/{total} killed")
        return 0 if not survived else 1


if __name__ == "__main__":
    sys.exit(main())
